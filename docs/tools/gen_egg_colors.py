#!/usr/bin/env python3
"""Generate `crates/umicraft-game/src/items/egg_table.rs` from the MCP 1.8 sources.

Spawn egg colours are the `EntityList.addMapping(Class, "Name", id, primary,
secondary)` calls with five arguments (the three-argument form registers an
entity without an egg). `ItemMonsterPlacer.getColorFromItemStack` reads them
back through `EntityList.entityEggs`.

Usage:
    python3 docs/tools/gen_egg_colors.py [OUTPUT]

`MCP_ROOT` (the directory holding `entity/`) defaults to
`../mcp/src/minecraft/net/minecraft` next to the repository.
"""

import os
import re
import sys

DEFAULT_MCP_ROOT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "mcp",
    "src", "minecraft", "net", "minecraft",
)
DEFAULT_OUT = "crates/umicraft-game/src/items/egg_table.rs"

EGG_CALL = re.compile(
    r'^\s+addMapping\(\w+\.class,\s*"\w+",\s*(\d+),\s*(\d+),\s*(\d+)\);', re.M
)


def egg_colors(text):
    """Return the sorted `(entity id, primary, secondary)` triples of the source."""
    triples = {int(i): (int(p), int(s)) for i, p, s in EGG_CALL.findall(text)}
    return [(i, *colors) for i, colors in sorted(triples.items())]


def render(triples):
    """Return the Rust source for the table."""
    lines = [
        "// SPDX-License-Identifier: MIT OR Apache-2.0",
        "",
        "//! Spawn egg colours, generated by `docs/tools/gen_egg_colors.py` from MCP"
        " `EntityList`. Do not edit by hand.",
        "",
        "/// `(entity id, primary colour, secondary colour)`, sorted by entity id.",
        "pub(super) static EGGS: &[(u8, u32, u32)] = &[",
    ]
    lines += [f"    ({i}, 0x{p:06X}, 0x{s:06X})," for i, p, s in triples]
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    root = os.environ.get("MCP_ROOT", os.path.normpath(DEFAULT_MCP_ROOT))
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    with open(os.path.join(root, "entity", "EntityList.java"), encoding="utf-8") as f:
        triples = egg_colors(f.read())
    with open(out, "w", encoding="utf-8") as f:
        f.write(render(triples))
    print(f"wrote {len(triples)} spawn eggs to {out}")


if __name__ == "__main__":
    main()
