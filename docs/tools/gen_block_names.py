#!/usr/bin/env python3
"""Generate `crates/umicraft-game/src/items/block_names.rs` from the MCP 1.8 sources.

The table maps every block of `Block.registerBlocks` to its registry name and
its unlocalised name (`setUnlocalizedName`, prefixed with `tile.` as
`Block.getUnlocalizedName` does). A registration that passes a local variable
takes the unlocalised name of that variable's last assignment; otherwise the
block class's constructor may set it (`BlockDaylightDetector`). A block that
never sets one is `tile.null`, as the reference prints its null field.

Usage:
    MCP_ROOT=/path/to/mcp/src/minecraft/net/minecraft \
        python3 docs/tools/gen_block_names.py [OUTPUT]
"""

import os
import re
import sys

REGISTER = re.compile(r'registerBlock\((\d+), (?:"([^"]+)"|AIR_ID), (.*)\);\s*$')
ASSIGN = re.compile(r'Block (\w+) = (.*);\s*$')
NAME = re.compile(r'setUnlocalizedName\("([^"]+)"\)')
CLASS = re.compile(r'new (Block\w+)\(')


def constructor_name(root, expression):
    """The name a block class sets in its own constructor, if any."""
    found = CLASS.search(expression)
    if not found:
        return None
    path = os.path.join(root, "block", found.group(1) + ".java")
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as file:
        name = re.search(r'this\.setUnlocalizedName\("([^"]+)"\)', file.read())
    return name.group(1) if name else None


def blocks(source, root):
    """`(id, registry name, unlocalised name)` in registration order."""
    variables = {}
    out = []
    for line in source.splitlines():
        line = line.strip()
        assign = ASSIGN.match(line)
        if assign:
            found = NAME.search(assign.group(2))
            if found:
                variables[assign.group(1)] = found.group(1)
            continue
        register = REGISTER.search(line)
        if not register:
            continue
        block_id, name, expression = register.groups()
        found = NAME.search(expression)
        unlocalized = found.group(1) if found else variables.get(expression.strip())
        if unlocalized is None:
            unlocalized = constructor_name(root, expression) or "null"
        out.append((int(block_id), name or "air", unlocalized))
    return out


def render(entries):
    rows = "\n".join(f'    ({i}, "{name}", "tile.{key}"),' for i, name, key in entries)
    return f"""// SPDX-License-Identifier: MIT OR Apache-2.0

//! Block registry and unlocalised names, generated by `docs/tools/gen_block_names.py` from MCP `Block.registerBlocks`. Do not edit by hand.

/// `(block id, registry name, unlocalised name)` sorted by id, e.g.
/// `(9, "water", "tile.water")`.
pub(super) static BLOCKS: &[(u16, &str, &str)] = &[
{rows}
];
"""


def main():
    root = os.environ.get("MCP_ROOT")
    if not root:
        sys.exit("set MCP_ROOT to the net/minecraft folder of the MCP sources")
    with open(os.path.join(root, "block", "Block.java"), encoding="utf-8") as file:
        entries = sorted(blocks(file.read(), root))
    output = sys.argv[1] if len(sys.argv) > 1 else "crates/umicraft-game/src/items/block_names.rs"
    with open(output, "w", encoding="utf-8") as file:
        file.write(render(entries))
    print(f"{len(entries)} blocks written to {output}")


if __name__ == "__main__":
    main()
