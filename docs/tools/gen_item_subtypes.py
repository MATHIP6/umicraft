#!/usr/bin/env python3
"""Generate `crates/umicraft-game/src/items/subtype_table.rs` from the MCP 1.8 sources.

The table lists the item ids whose `Item.getHasSubtypes` is true, which the
advanced tooltip shows as `#0276/0` instead of `#0276`:

* block items registered with a class that sets it in its constructor or in
  a superclass (`ItemCloth`, `ItemMultiTexture` and its `ItemAnvilBlock` and
  `ItemDoublePlant`, `ItemSlab`, `ItemLeaves`, `ItemSnow`), or with
  `ItemColored(block, true)`; `Blocks.java` gives each block's registry name
  and `Block.registerBlocks` its id;
* items registered with a class that sets it in its constructor, or with
  `setHasSubtypes(true)` chained at the registration.

Usage:
    MCP_ROOT=/path/to/mcp/src/minecraft/net/minecraft \
        python3 docs/tools/gen_item_subtypes.py [OUTPUT]
"""

import os
import re
import sys

ITEM_BLOCK = re.compile(r'registerItemBlock\(Blocks\.(\w+), \(*new (\w+)\(([^)]*)\)')
ITEM = re.compile(r'registerItem\((\d+), "[^"]+", (.*)$')
FIELD = re.compile(r'(\w+) = (?:\(\w+\))?getRegisteredBlock\("([^"]+)"\)')
BLOCK_ID = re.compile(r'registerBlock\((\d+), "([^"]+)"')
NEW_CLASS = re.compile(r'new (Item\w+)\(')


def read(root, *parts):
    with open(os.path.join(root, *parts), encoding="utf-8") as file:
        return file.read()


def class_sets_subtypes(root, name, cache):
    """Whether the class `name` (or a superclass in `item/`) sets subtypes."""
    if name in cache:
        return cache[name]
    path = os.path.join(root, "item", name + ".java")
    result = False
    if os.path.exists(path) and name != "Item":
        source = read(root, "item", name + ".java")
        if "setHasSubtypes(true)" in source and "if (hasSubtypes)" not in source:
            result = True
        else:
            parent = re.search(r'class \w+ extends (\w+)', source)
            result = bool(parent) and class_sets_subtypes(root, parent.group(1), cache)
    cache[name] = result
    return result


def subtypes(root):
    fields = dict(FIELD.findall(read(root, "init", "Blocks.java")))
    block_ids = {name: int(i) for i, name in BLOCK_ID.findall(read(root, "block", "Block.java"))}
    ids = set()
    cache = {}
    for line in read(root, "item", "Item.java").splitlines():
        block = ITEM_BLOCK.search(line)
        if block:
            field, cls, args = block.groups()
            colored = cls == "ItemColored" and args.strip().endswith("true")
            if colored or class_sets_subtypes(root, cls, cache):
                ids.add(block_ids[fields[field]])
            continue
        item = ITEM.search(line)
        if item:
            item_id, expression = item.groups()
            new = NEW_CLASS.search(expression)
            chained = "setHasSubtypes(true)" in expression
            if chained or (new and class_sets_subtypes(root, new.group(1), cache)):
                ids.add(int(item_id))
    return sorted(ids)


def render(ids):
    rows = "\n".join(f"    {i}," for i in ids)
    return f"""// SPDX-License-Identifier: MIT OR Apache-2.0

//! Item ids with subtypes, generated by `docs/tools/gen_item_subtypes.py` from MCP `Item.registerItems`. Do not edit by hand.

/// The ids whose `Item.getHasSubtypes` is true, sorted.
pub(super) static SUBTYPES: &[u16] = &[
{rows}
];
"""


def main():
    root = os.environ.get("MCP_ROOT")
    if not root:
        sys.exit("set MCP_ROOT to the net/minecraft folder of the MCP sources")
    ids = subtypes(root)
    output = sys.argv[1] if len(sys.argv) > 1 else "crates/umicraft-game/src/items/subtype_table.rs"
    with open(output, "w", encoding="utf-8") as file:
        file.write(render(ids))
    print(f"{len(ids)} items written to {output}")


if __name__ == "__main__":
    main()
