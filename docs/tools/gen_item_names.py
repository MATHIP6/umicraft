#!/usr/bin/env python3
"""Generate `crates/umicraft-game/src/items/name_table.rs` from the MCP 1.8 sources.

The 1.8 language file is keyed by the *unlocalised* names the game gives its
items (`item.swordDiamond.name`, `tile.wool.red.name`), not by registry names.
This script extracts, for every item id registered in `Item.registerItems`:

* block items: `"tile." + Block.setUnlocalizedName(..)` (`ItemBlock` asks its
  block), looked up through `Block.registerBlocks()`;
* other items: `"item." + Item.setUnlocalizedName(..)`.

It also extracts the spawn-egg entity names from `EntityList` (`addMapping`
with egg colours), which the egg's display name appends.

Usage:
    MCP_ROOT=/path/to/mcp/src/minecraft/net/minecraft \
        python3 docs/tools/gen_item_names.py [output.rs]

Run `cargo fmt` on the output afterwards, like `gen_item_data.py`.
"""

import os
import re
import sys

DEFAULT_OUT = "crates/umicraft-game/src/items/name_table.rs"

MCP_ROOT = os.environ.get("MCP_ROOT")
if not MCP_ROOT:
    sys.exit("set MCP_ROOT to .../mcp/src/minecraft/net/minecraft")


def read(relative):
    """Return the text of a source file below MCP_ROOT."""
    with open(os.path.join(MCP_ROOT, relative), encoding="utf-8") as handle:
        return handle.read()


def unlocalised(expression):
    """Return the last `setUnlocalizedName("x")` argument of `expression`, or None."""
    names = re.findall(r'setUnlocalizedName\("(\w+)"\)', expression)
    return names[-1] if names else None


def block_unlocalised(expression):
    """Return the name a block expression sets, falling back to its constructor.

    A few blocks (`BlockDaylightDetector`, `BlockDoublePlant`) name themselves
    in their own constructor instead of at the registration site.
    """
    name = unlocalised(expression)
    if name:
        return name
    cls = re.search(r"new (\w+)\(", expression).group(1)
    return unlocalised(read(f"block/{cls}.java"))


def block_names():
    """Return ({Blocks field -> block registry name}, {registry name -> (id, unlocalised)})."""
    blocks_java = read("init/Blocks.java")
    fields = dict(re.findall(r'(\w+) = (?:\(\w+\))?getRegisteredBlock\("(\w+)"\)', blocks_java))
    block_java = read("block/Block.java")
    body = block_java[block_java.index("public static void registerBlocks()"):]
    variables = dict(re.findall(r"^        Block (\w+) = (.+?);\n", body, re.M))
    registered = {}
    for ident, name, expression in re.findall(
        r'registerBlock\((\d+), "(\w+)", (.+)\);\n', body
    ):
        expression = variables.get(expression.strip(), expression)
        registered[name] = (int(ident), block_unlocalised(expression))
    return fields, registered


def item_names():
    """Return {item id -> full unlocalised name} for every registered item."""
    item_java = read("item/Item.java")
    body = item_java[item_java.index("public static void registerItems()"):]
    body = body[:body.index("private static void registerItemBlock")]
    variables = dict(re.findall(r"^        Item (\w+) = (.+?);\n", body, re.M))
    fields, registered = block_names()
    names = {}
    for field in re.findall(r"^        registerItemBlock\(Blocks\.(\w+)", body, re.M):
        ident, name = registered[fields[field]]
        names[ident] = f"tile.{name}"
    for ident, expression in re.findall(r'^        registerItem\((\d+), "\w+", (.+)\);\n', body, re.M):
        expression = variables.get(expression.strip(), expression)
        names[int(ident)] = f"item.{unlocalised(expression)}"
    return names


def entity_names():
    """Return {entity id -> entity name} for the mobs that have a spawn egg."""
    entity_list = read("entity/EntityList.java")
    return {
        int(ident): name
        for name, ident in re.findall(
            r'addMapping\(Entity\w+\.class, "(\w+)", (\d+), \d+, \d+\)', entity_list
        )
    }


def render(items, entities):
    """Render the Rust source of `name_table.rs`."""
    out = [
        "// SPDX-License-Identifier: MIT OR Apache-2.0",
        "",
        "//! Unlocalised item names and spawn-egg entity names, generated by "
        "`docs/tools/gen_item_names.py` from MCP `Item.registerItems` and "
        "`EntityList`. Do not edit by hand.",
        "",
        "/// `(item id, unlocalised name)` sorted by id, e.g. `(276, \"item.swordDiamond\")`.",
        "pub(super) static BASE: &[(u16, &str)] = &[",
    ]
    out += [f'    ({ident}, "{items[ident]}"),' for ident in sorted(items)]
    out += [
        "];",
        "",
        "/// `(entity id, entity name)` sorted by id, for the spawn egg name.",
        "pub(super) static ENTITIES: &[(u8, &str)] = &[",
    ]
    out += [f'    ({ident}, "{entities[ident]}"),' for ident in sorted(entities)]
    out += ["];", ""]
    return "\n".join(out)


def main():
    items, entities = item_names(), entity_names()
    assert not any("None" in name for name in items.values())
    assert items[276] == "item.swordDiamond" and items[35] == "tile.cloth"
    assert items[383] == "item.monsterPlacer" and entities[50] == "Creeper"
    out_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(render(items, entities))
    print(f"{len(items)} items, {len(entities)} spawn-egg entities")


if __name__ == "__main__":
    main()
