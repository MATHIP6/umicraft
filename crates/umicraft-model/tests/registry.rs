fn state(id: u16, metadata: u8) -> (&'static str, &'static str) {
    let definition = definition(id).unwrap_or_else(|| panic!("id {id} is not in the registry"));
    let state = definition
        .state(metadata)
        .unwrap_or_else(|| panic!("id {id} metadata {metadata:#04x} has no state rule"));
    (state.blockstate, state.variant)
}

fn assert_state(id: u16, metadata: u8, blockstate: &str, variant: &str) {
    assert_eq!(
        state(id, metadata),
        (blockstate, variant),
        "id {id} metadata {metadata:#04x}"
    );
}

fn assert_colours(id: u16, suffix: &str) {
    for (metadata, colour) in COLOURS.iter().enumerate() {
        let document = format!("{colour}_{suffix}");
        assert_state(id, metadata as u8, &document, "normal");
    }
}

fn is_canonical_variant(variant: &str) -> bool {
    if matches!(variant, "normal" | "all") {
        return true;
    }

    let mut previous: Option<&str> = None;
    for pair in variant.split(',') {
        let Some((name, value)) = pair.split_once('=') else {
            return false;
        };
        if name.is_empty() || value.is_empty() || value.contains('=') {
            return false;
        }
        if let Some(previous) = previous {
            if name <= previous {
                return false;
            }
        }
        previous = Some(name);
    }
    previous.is_some()
}

