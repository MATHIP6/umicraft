#[test]
fn metadata_masks_ignore_bits_outside_the_mask() {
    // Logs use the low nibble for wood and axis; bits 4..7 are ignored.
    assert_state(17, 0xF0, "oak_log", "axis=y");
    assert_state(17, 0xF4, "oak_log", "axis=x");
    assert_state(17, 0xF8, "oak_log", "axis=z");
    assert_state(17, 0xFC, "oak_log", "axis=none");
    assert_state(17, 0xF5, "spruce_log", "axis=x");

    // Leaves use only bits 0..1; the decay and check bits are dropped.
    assert_state(18, 0xF4, "oak_leaves", "normal");
    assert_state(18, 0xFF, "jungle_leaves", "normal");

    // Double stone slabs use bit 3 for seamless; single slabs use it for half.
    assert_state(43, 0x10, "stone_double_slab", "normal");
    assert_state(43, 0x18, "stone_double_slab", "all");
    assert_state(44, 0x10, "stone_slab", "half=bottom");
    assert_state(44, 0x18, "stone_slab", "half=top");

    // Stairs use bits 0..2.
    assert_state(
        53,
        0xF8,
        "oak_stairs",
        "facing=east,half=bottom,shape=straight",
    );
    assert_state(
        53,
        0xFC,
        "oak_stairs",
        "facing=east,half=top,shape=straight",
    );

    // Wool and snow-layer rules use their full masks.
    assert_state(35, 0xF3, "light_blue_wool", "normal");
    assert_state(35, 0xFF, "black_wool", "normal");
    assert_state(78, 0xF0, "snow_layer", "layers=1");
    assert_state(78, 0xFF, "snow_layer", "layers=8");

    // Quartz clamps enum metadata above index 4 to the default document.
    assert_state(155, 0xF2, "quartz_column", "axis=y");
    assert_state(155, 0xF3, "quartz_column", "axis=x");
    assert_state(155, 0xF4, "quartz_column", "axis=z");
    assert_state(155, 0xFF, "quartz_block", "normal");

    // New woods use the low two bits; indices 6/7 clamp to oak.
    assert_state(161, 0xF4, "acacia_leaves", "normal");
    assert_state(161, 0xF5, "dark_oak_leaves", "normal");
    assert_state(161, 0xF6, "oak_leaves", "normal");
    assert_state(162, 0xF2, "oak_log", "axis=y");
    assert_state(162, 0xF7, "oak_log", "axis=x");
}

